CREATE TABLE IF NOT EXISTS orders (
  id VARCHAR(36) PRIMARY KEY,
  order_number VARCHAR(40) NOT NULL UNIQUE,
  idempotency_key VARCHAR(100) NOT NULL UNIQUE,
  request_hash VARCHAR(64) NOT NULL,
  customer_name VARCHAR(100) NOT NULL,
  customer_email VARCHAR(254) NOT NULL,
  customer_phone VARCHAR(10) NOT NULL,
  address_line1 VARCHAR(160) NOT NULL,
  address_line2 VARCHAR(160) NOT NULL DEFAULT '',
  address_city VARCHAR(80) NOT NULL,
  address_state VARCHAR(80) NOT NULL,
  address_pin VARCHAR(6) NOT NULL,
  items_json TEXT NOT NULL,
  subtotal INTEGER NOT NULL,
  shipping INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('pending', 'paid', 'failed', 'cod', 'shipped', 'delivered', 'cancelled', 'refunded')),
  payment_method VARCHAR(10) NOT NULL CHECK (payment_method IN ('online', 'cod')),
  razorpay_order_id VARCHAR(64) UNIQUE,
  razorpay_payment_id VARCHAR(64) UNIQUE,
  razorpay_refund_id VARCHAR(64),
  refund_status VARCHAR(20),
  created_at VARCHAR(40) NOT NULL,
  updated_at VARCHAR(40) NOT NULL,
  paid_at VARCHAR(40),
  shipped_at VARCHAR(40),
  delivered_at VARCHAR(40),
  cancelled_at VARCHAR(40),
  refunded_at VARCHAR(40),
  email_claimed_at VARCHAR(40),
  email_sent_at VARCHAR(40)
);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders(created_at);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
